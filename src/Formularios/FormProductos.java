    private void btnGuardarListaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarListaActionPerformed
        String codigo = txtCodigo.getText().trim(); 
    String nombre = txtNombre.getText().trim();
    String cantidadTxt = txtCantidad.getText().trim();
    String precioTxt = txtPrecio.getText().trim().replace(',', '.');
    String categoria = (String) cbxCategoria.getSelectedItem();

    // Validaciones básicas
    if ("Todos".equalsIgnoreCase(categoria)) {
        JOptionPane.showMessageDialog(this, "Debe seleccionar una categoría específica (Pieza o Equipo)");
        return;
    }

    if (nombre.isEmpty() || cantidadTxt.isEmpty() || precioTxt.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos principales");
        return;
    }

    int cantidad;
    float precio;
    try {
        cantidad = Integer.parseInt(cantidadTxt);
        precio = Float.parseFloat(precioTxt);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Cantidad y precio deben ser números válidos");
        return;
    }

    // Crear el producto usando el código del txtCodigo (ej: P-001)
    Producto producto = new Producto();
    producto.setCodigo(codigo);
    producto.setNombre(nombre);
    producto.setCategoria(categoria);
    producto.setCantidad(cantidad);
    producto.setPrecio(precio);

    if ("Pieza".equalsIgnoreCase(categoria)) {
        producto.setSocketPuerto(txtSocketPuerto.getText().trim());
    } else if ("Equipo".equalsIgnoreCase(categoria)) {
        try {
            producto.setAniosGarantia(Integer.parseInt(txtAniosGarantia.getText().trim()));
        } catch (NumberFormatException e) {
            producto.setAniosGarantia(0);
        }
    }

    // 1. Guardar SOLO en la lista temporal en memoria
    listaTemporal.add(producto);

    // 2. Mostrar la fila en la JTable
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tablaProductos.getModel();
    model.addRow(new Object[]{
        producto.getCodigo(),
        producto.getNombre(),
        producto.getCantidad(),
        producto.getPrecio()
    });

    // 3. Incrementar el código autoincremental para el siguiente producto (P-002)
    contadorCodigo++;
    mostrarSiguienteCodigo();

    // 4. Limpiar los campos para un nuevo ingreso
    txtNombre.setText("");
    txtCantidad.setText("");
    txtPrecio.setText("");
    txtSocketPuerto.setText("");
    txtAniosGarantia.setText("");
    cbxCategoria.setSelectedIndex(0);
    }//GEN-LAST:event_btnGuardarListaActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        // Obtener el índice de la fila seleccionada en la tabla
        int filaSeleccionada = tablaProductos.getSelectedRow();

        if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Por favor, seleccione un producto de la lista para eliminar.");
        return;
        }

        // Confirmar eliminación
        int confirmacion = JOptionPane.showConfirmDialog(
        this, 
        "¿Está seguro de eliminar este producto de la lista temporal?", 
        "Confirmar Eliminación", 
        JOptionPane.YES_NO_OPTION
        );

        if (confirmacion == JOptionPane.YES_OPTION) {
        // 1. Remover de la lista temporal en memoria
        listaTemporal.remove(filaSeleccionada);

        // 2. Recalcular correlativos y actualizar la JTable
        recalcularCodigos();

        JOptionPane.showMessageDialog(this, "Producto eliminado y correlativo actualizado.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

