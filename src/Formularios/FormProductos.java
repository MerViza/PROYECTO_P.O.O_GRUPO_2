    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        if (listaTemporal.isEmpty()) {
        JOptionPane.showMessageDialog(this, "La lista está vacía. Agregue productos con el botón LISTAR antes de confirmar.");
        return;
    }

    int guardados = 0;
    int errores = 0;

    // Recorrer la lista en memoria e guardar cada uno en la BD
    for (Producto producto : listaTemporal) {
        if (productoDAO.insertar(producto)) {
            guardados++;
        } else {
            errores++;
        }
    }

    if (errores == 0) {
        JOptionPane.showMessageDialog(this, "¡Éxito! Se guardaron " + guardados + " producto(s) en la base de datos.");
        listaTemporal.clear(); // Se vacía la lista temporal
    } else {
        JOptionPane.showMessageDialog(this, "Se guardaron " + guardados + " producto(s), pero " + errores + " fallaron.");
    }
    }//GEN-LAST:event_btnConfirmarActionPerformed

