    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtCantidad.setText("");
        txtPrecio.setText("");
        txtSocketPuerto.setText("");
        txtAniosGarantia.setText("");
        cbxCategoria.setSelectedIndex(0);
        actualizarVisibilidadCampos();
        txtCodigo.requestFocus();
    
}
    
    // Método para mostrar el código autogenerado en el txtCodigo
    private void mostrarSiguienteCodigo() {
        txtCodigo.setText(String.format("P-%03d", contadorCodigo));
    }
    
  private void actualizarVisibilidadCampos() {
    String categoria = (String) cbxCategoria.getSelectedItem();

    if ("Todos".equalsIgnoreCase(categoria)) {
        // Habilita ambos campos
        txtSocketPuerto.setEnabled(true);
        txtAniosGarantia.setEnabled(true);
    } else if ("Pieza".equalsIgnoreCase(categoria)) {
        // Solo habilita Socket / Puerto
        txtSocketPuerto.setEnabled(true);
        txtAniosGarantia.setEnabled(false);
        txtAniosGarantia.setText("");
    } else if ("Equipo".equalsIgnoreCase(categoria)) {
        // Solo habilita Años de Garantía
        txtSocketPuerto.setEnabled(false);
        txtSocketPuerto.setText("");
        txtAniosGarantia.setEnabled(true);
    }
}
    private void mostrarEnTabla(List<Producto> lista) {
    DefaultTableModel modelo = (DefaultTableModel) tablaProductos.getModel();
    modelo.setRowCount(0); // borra las filas anteriores (incluidas las 4 vacías del diseñador)

    for (Producto p : lista) {
        modelo.addRow(new Object[] {
            p.getCodigo(),
            p.getNombre(),
            p.getCantidad(),
            p.getPrecio()
        });
        }
    }

    private void cargarTabla() {
        mostrarEnTabla(productoDAO.listar());
    }
    
    private void recalcularCodigos() {
    // Obtener la base inicial según lo que ya existe guardado en la BD MySQL
    int baseCodigo = productoDAO.obtenerUltimoNumeroCodigo();

    // 1. Recorrer la lista en memoria y reasignar correlativamente los códigos
    for (int i = 0; i < listaTemporal.size(); i++) {
        int nuevoNumero = baseCodigo + 1 + i;
        String nuevoCodigo = String.format("P-%03d", nuevoNumero);
        listaTemporal.get(i).setCodigo(nuevoCodigo);
    }

    // 2. Ajustar el contador para el siguiente elemento que el usuario vaya a registrar
    contadorCodigo = baseCodigo + 1 + listaTemporal.size();
    mostrarSiguienteCodigo();

    // 3. Refrescar los datos mostrados en la JTable
    DefaultTableModel model = (DefaultTableModel) tablaProductos.getModel();
    model.setRowCount(0); // Limpiar vista de la tabla

    for (Producto p : listaTemporal) {
        model.addRow(new Object[]{
            p.getCodigo(),
            p.getNombre(),
            p.getCantidad(),
            p.getPrecio()
        });
    }
}
