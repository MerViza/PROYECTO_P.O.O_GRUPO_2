    private void btnGenerarTxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarTxtActionPerformed
      
                String categoria = cbxCategoria.getSelectedItem().toString();
        List<Producto> lista = productoDAO.listarBajoStock(UMBRAL, categoria);

        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay productos con bajo stock para el reporte",
                    "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String marca = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd_HHmm"));

        JFileChooser selector = new JFileChooser();
        selector.setDialogTitle("Guardar reporte de bajo stock");
        selector.setSelectedFile(new File("reporte_bajo_stock_" + marca + ".txt"));

        if (selector.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
            return; // el usuario canceló
        }

        File archivo = selector.getSelectedFile();
        if (!archivo.getName().toLowerCase().endsWith(".txt")) {
            archivo = new File(archivo.getParentFile(), archivo.getName() + ".txt");
        }

        if (archivo.exists()) {
            int respuesta = JOptionPane.showConfirmDialog(this,
                    "El archivo ya existe. ¿Desea reemplazarlo?",
                    "Confirmar", JOptionPane.YES_NO_OPTION);
            if (respuesta != JOptionPane.YES_OPTION) {
                return;
            }
        }

        try {
            new ReporteBajoStock(lista, UMBRAL, categoria).guardar(archivo);
            JOptionPane.showMessageDialog(this, "Reporte guardado en:\n" + archivo.getAbsolutePath());
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "No se pudo guardar el reporte: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnGenerarTxtActionPerformed

