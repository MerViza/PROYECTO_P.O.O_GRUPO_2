    private void configurarTabla() {
    DefaultTableModel modelo = new DefaultTableModel(
            new String[] {"Código", "Nombre", "Categoría", "Stock", "Estado"}, 0) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };
    tablaBajoStock.setModel(modelo);
    tablaBajoStock.setRowHeight(24);
    tablaBajoStock.getTableHeader().setReorderingAllowed(false);

    tablaBajoStock.getColumnModel().getColumn(4).setCellRenderer(new DefaultTableCellRenderer() {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value,
                boolean isSelected, boolean hasFocus, int row, int column) {
            Component c = super.getTableCellRendererComponent(
                    table, value, isSelected, hasFocus, row, column);
            if (!isSelected) {
                if ("Agotado".equals(value)) {
                    c.setBackground(new Color(252, 235, 235));
                    c.setForeground(new Color(163, 45, 45));
                } else {
                    c.setBackground(new Color(250, 238, 218));
                    c.setForeground(new Color(133, 79, 11));
                }
            }
            return c;
        }
    });
}

    private void cargarDatos() {
        String categoria = cbxCategoria.getSelectedItem().toString();
        List<Producto> lista = productoDAO.listarBajoStock(UMBRAL, categoria);

        DefaultTableModel modelo = (DefaultTableModel) tablaBajoStock.getModel();
        modelo.setRowCount(0);

        for (Producto p : lista) {
            String estado = (p.getCantidad() == 0) ? "Agotado" : "Bajo";
            modelo.addRow(new Object[] {
                p.getCodigo(),
                p.getNombre(),
                p.getCategoria(),
                p.getCantidad(),
                estado
            });
        }

        lblCantBajo.setText(String.valueOf(lista.size()));
    }


