    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText().trim();
    String nombre = txtNombre.getText().trim();
    String cantidadTxt = txtCantidad.getText().trim();
    String precioTxt = txtPrecio.getText().trim().replace(',', '.');
    String categoria = (String) cbxCategoria.getSelectedItem();

    // 1. Validaciones
    if ("Todos".equalsIgnoreCase(categoria)) {
        JOptionPane.showMessageDialog(this, "Debe seleccionar una categoría específica (Pieza o Equipo)");
        return;
    }

    if (nombre.isEmpty() || cantidadTxt.isEmpty() || precioTxt.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos principales");
        return;
    }

    int cantidad;
    float precio;
    try {
        cantidad = Integer.parseInt(cantidadTxt);
        precio = Float.parseFloat(precioTxt);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Cantidad y precio deben ser números válidos");
        return;
    }

    if (cantidad < 0 || precio <= 0) {
        JOptionPane.showMessageDialog(this, "La cantidad no puede ser negativa y el precio debe ser mayor a 0");
        return;
    }

    // 2. Construir objeto Producto
    Producto producto = new Producto();
    producto.setCodigo(codigo);
    producto.setNombre(nombre);
    producto.setCategoria(categoria);
    producto.setCantidad(cantidad);
    producto.setPrecio(precio);

    if ("Pieza".equalsIgnoreCase(categoria)) {
        String socket = txtSocketPuerto.getText().trim();
        if (socket.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el Socket / Puerto");
            return;
        }
        producto.setSocketPuerto(socket);
    } else if ("Equipo".equalsIgnoreCase(categoria)) {
        String garantiaTxt = txtAniosGarantia.getText().trim();
        if (garantiaTxt.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese los Años de Garantía");
            return;
        }
        try {
            producto.setAniosGarantia(Integer.parseInt(garantiaTxt));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Los años de garantía deben ser un número entero");
            return;
        }
    }

    // 3. Guardado DIRECTO en Base de Datos
    if (productoDAO.insertar(producto)) {
        JOptionPane.showMessageDialog(this, "¡Producto guardado exitosamente en la BD con el código " + codigo + "!");
        limpiarCampos(); // Limpia campos y actualiza el txtCodigo al siguiente correlativo
    } else {
        JOptionPane.showMessageDialog(this, "Error al guardar el producto en la base de datos.");
    }
    }//GEN-LAST:event_btnConfirmarActionPerformed

