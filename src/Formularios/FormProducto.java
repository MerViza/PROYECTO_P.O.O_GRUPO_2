    // Consulta el último número en la BD y muestra el siguiente (ej: P-003)
    private void cargarSiguienteCodigo() {
        int ultimoNumero = productoDAO.obtenerUltimoNumeroCodigo();
        contadorCodigo = ultimoNumero + 1;
        txtCodigo.setText(String.format("P-%03d", contadorCodigo));
    }
    
    
    private void limpiarCampos() {
    txtNombre.setText("");
    txtCantidad.setText("");
    txtPrecio.setText("");
    txtSocketPuerto.setText("");
    txtAniosGarantia.setText("");
    cbxCategoria.setSelectedIndex(0); // Vuelve a "Todos" o categoría por defecto
    
    actualizarVisibilidadCampos(); // <--- Añadir esta línea
    
    // Recarga el código por si hubo cambios o inserciones
    cargarSiguienteCodigo();
    
    txtNombre.requestFocus(); // Posiciona el cursor en Nombre
}
    
    private void actualizarVisibilidadCampos() {
    String categoria = (String) cbxCategoria.getSelectedItem();

    if ("Todos".equalsIgnoreCase(categoria)) {
        // Habilita ambos campos
        txtSocketPuerto.setEnabled(true);
        txtAniosGarantia.setEnabled(true);
    } else if ("Pieza".equalsIgnoreCase(categoria)) {
        // Solo habilita Socket / Puerto
        txtSocketPuerto.setEnabled(true);
        txtAniosGarantia.setEnabled(false);
        txtAniosGarantia.setText("");
    } else if ("Equipo".equalsIgnoreCase(categoria)) {
        // Solo habilita Años de Garantía
        txtSocketPuerto.setEnabled(false);
        txtSocketPuerto.setText("");
        txtAniosGarantia.setEnabled(true);
    }
}
