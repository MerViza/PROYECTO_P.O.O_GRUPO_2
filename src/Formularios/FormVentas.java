    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
       int filaSel = tblCarrito.getSelectedRow();
    if (filaSel == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto del carrito para modificar su cantidad.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int cantidadAQuitar = 0;
    try {
        cantidadAQuitar = Integer.parseInt(txtCantidadCarrito.getText().trim());
        if (cantidadAQuitar <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad a quitar debe ser mayor a 0.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingrese un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 1. Obtener la fila seleccionada del carrito
    DetalleVenta det = listaCarrito.get(filaSel);
    int cantidadActualEnCarrito = det.getCantidad();

    // 2. Validar que no se intente quitar más de lo que hay en el carrito
    if (cantidadAQuitar > cantidadActualEnCarrito) {
        JOptionPane.showMessageDialog(this, 
            "No puede quitar " + cantidadAQuitar + " unidades. Solo hay " + cantidadActualEnCarrito + " en el carrito.", 
            "Cantidad Excedida", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3. Buscar el producto correspondiente en el stock local
    Producto prodStock = null;
    for (Producto p : listaProductosLocal) {
        if (p.getCodigo().equalsIgnoreCase(det.getCodigoProducto())) {
            prodStock = p;
            break;
        }
    }

    if (prodStock != null) {
        // 4. Sumar la cantidad devuelta al stock local
        prodStock.setCantidad(prodStock.getCantidad() + cantidadAQuitar);

        // 5. Ajustar o eliminar del carrito
        if (cantidadAQuitar == cantidadActualEnCarrito) {
            // Si quita el total exacto (ej. quita 40 de 40), se elimina la fila del carrito
            listaCarrito.remove(filaSel);
        } else {
            // Si quita solo una parte (ej. quita 25 de 40), el carrito queda con la diferencia (15)
            det.setCantidad(cantidadActualEnCarrito - cantidadAQuitar);
        }

        // 6. Refrescar tablas, recalcular totales y mantener el campo habilitado
        actualizarTablaStockActual();
        actualizarTablaCarrito();
        calcularTotalesCarrito();

        txtCantidadCarrito.setText("");
        txtCantidadCarrito.setEnabled(true);
        txtCantidadCarrito.setEditable(true);
    }
    }//GEN-LAST:event_btnEditarActionPerformed

