    private void cargarProductosDesdeBD() {
    // 1. Traer los productos reales de la BD solo una vez
    listaProductosLocal = productoDAO.buscarOFiltrar("", "Todo"); // O usar buscarOFiltrar("", "Todo")

    // 2. Renderizar la tabla de la izquierda (Stock Actual)
    actualizarTablaStockActual();
}
    private void actualizarTablaStockActual() {
    DefaultTableModel model = (DefaultTableModel) tblStockActual.getModel(); // Nombre de tu tabla izquierda
    model.setRowCount(0);

    for (Producto p : listaProductosLocal) {
        model.addRow(new Object[]{
            p.getCodigo(),
            p.getNombre(),
            p.getCantidad(), // Muestra la cantidad local disponible
            String.format("%.2f", p.getPrecio())
        });
    }
}
    private void calcularTotalesCarrito() {
    float subtotal = 0.0f;

    for (DetalleVenta det : listaCarrito) {
        subtotal += (det.getCantidad() * det.getPrecioUnitario());
    }

    float igv = subtotal * TASA_IGV;
    float total = subtotal + igv;

    // Asignar los montos con formato decimal
    txtSubtotal.setText(String.format("S/ %.2f", subtotal));
    txtIGV.setText(String.format("S/ %.2f", igv));
    txtTotal.setText(String.format("S/ %.2f", total));
}
    
    private void actualizarTablaCarrito() {
    DefaultTableModel model = (DefaultTableModel) tblCarrito.getModel(); // Nombre de tu tabla derecha
    model.setRowCount(0);

    for (DetalleVenta det : listaCarrito) {
        model.addRow(new Object[]{
            det.getCodigoProducto(),
            det.getNombreProducto(),
            det.getCantidad(),
            String.format("%.2f", det.getPrecioUnitario())
        });
    }
}
    
    
