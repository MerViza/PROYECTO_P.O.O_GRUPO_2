    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        // 1. Validar que haya una fila seleccionada en la tabla Stock Actual
    int filaSeleccionada = tblStockActual.getSelectedRow();
    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla Stock Actual.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Validar que la cantidad ingresada sea un número entero válido
    int cantidadAAgregar = 0;
    try {
        String textoCantidad = txtCantidad.getText().trim(); // El JTextField debajo de Stock Actual
        if (textoCantidad.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la cantidad a agregar.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }
        cantidadAAgregar = Integer.parseInt(textoCantidad);
        if (cantidadAAgregar <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingrese una cantidad numérica entera válida.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 3. Obtener el producto seleccionado de la lista en memoria
    Producto prodSeleccionado = listaProductosLocal.get(filaSeleccionada);
    int stockDisponible = prodSeleccionado.getCantidad();

    // 4. VALIDACIÓN DE STOCK DISPONIBLE (Ej: Pide 21 pero solo hay 20)
    if (cantidadAAgregar > stockDisponible) {
        JOptionPane.showMessageDialog(this, 
            "Stock insuficiente. Solo quedan " + stockDisponible + " unidades disponibles de este producto.", 
            "Validación de Stock", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 5. RESTAR STOCK LOCALMENTE (En la lista en memoria, NO en BD)
    prodSeleccionado.setCantidad(stockDisponible - cantidadAAgregar);

    // 6. AGREGAR / ACUMULAR EN EL CARRITO DE COMPRAS
    boolean existeEnCarrito = false;
    for (DetalleVenta det : listaCarrito) {
        if (det.getCodigoProducto().equalsIgnoreCase(prodSeleccionado.getCodigo())) {
            det.setCantidad(det.getCantidad() + cantidadAAgregar);
            existeEnCarrito = true;
            break;
        }
    }

    if (!existeEnCarrito) {
        listaCarrito.add(new DetalleVenta(
            prodSeleccionado.getCodigo(),
            prodSeleccionado.getNombre(),
            cantidadAAgregar,
            prodSeleccionado.getPrecio()
        ));
    }

    // REFRESCAR TABLAS Y RECALCULAR OBLIGATORIAMENTE
    actualizarTablaStockActual();
    actualizarTablaCarrito();
    calcularTotalesCarrito(); // <-- ¡ESTA LÍNEA DEBE ESTAR AQUÍ!

    txtCantidadCarrito.setText("");

    // Limpiar el campo de texto
    txtCantidad.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

