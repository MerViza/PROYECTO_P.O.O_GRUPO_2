    private void cargarDatosProducto() {
        // Campos informativos (Solo lectura / Etiquetas)
        txtCodigo.setText(producto.getCodigo());
        txtCodigo.setEditable(false);
        
        txtNombre.setText(producto.getNombre());
        txtNombre.setEditable(false);

        txtCategoria.setText(producto.getCategoria() != null ? producto.getCategoria() : "-");
        txtCategoria.setEditable(false);

        txtSocketPuerto.setText(producto.getSocketPuerto() != null && !producto.getSocketPuerto().trim().isEmpty() 
                                ? producto.getSocketPuerto() : "N/A");
        txtSocketPuerto.setEditable(false);

        txtGarantia.setText(producto.getAniosGarantia() != null 
                            ? producto.getAniosGarantia() + " año(s)" : "N/A");
        txtGarantia.setEditable(false);

        // Campos editables (Precio y Cantidad/Stock)
        txtPrecio.setText(String.valueOf(producto.getPrecio()));
        txtCantidad.setText(String.valueOf(producto.getCantidad()));
    }
