    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Validar y obtener el nuevo Precio
            String textoPrecio = txtPrecio.getText().trim().replace(',', '.');
            if (textoPrecio.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe ingresar un precio.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;
            }

            float nuevoPrecio = Float.parseFloat(textoPrecio);
            if (nuevoPrecio < PRECIO_MINIMO || nuevoPrecio > PRECIO_MAXIMO) {
                JOptionPane.showMessageDialog(this, 
                    "El precio debe estar en el rango de S/ " + PRECIO_MINIMO + " y S/ " + PRECIO_MAXIMO + ".", 
                    "Precio Inválido", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 2. Validar y obtener el nuevo Stock (Cantidad)
            String textoCantidad = txtCantidad.getText().trim();
            if (textoCantidad.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe ingresar una cantidad de stock.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int nuevoStock = Integer.parseInt(textoCantidad);
            if (nuevoStock < STOCK_MINIMO || nuevoStock > STOCK_MAXIMO) {
                JOptionPane.showMessageDialog(this, 
                    "El stock debe estar entre " + STOCK_MINIMO + " y " + STOCK_MAXIMO + " unidades.", 
                    "Stock Inválido", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 3. Modificar el objeto producto con los nuevos datos
            producto.setPrecio(nuevoPrecio);
            producto.setCantidad(nuevoStock);

            // 4. Guardar los cambios en la base de datos usando ProductoDAO
            if (dao.actualizar(producto)) {
                JOptionPane.showMessageDialog(this, "¡Producto actualizado con éxito!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                
                // Actualiza la tabla en el formulario principal y cierra este diálogo
                if (parentForm != null) {
                    parentForm.cargarTabla();
                }
                this.dispose(); // Cierra el formulario de edición
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo actualizar el producto en la base de datos.", "Error BD", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese valores numéricos válidos en Precio y Stock.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

