        private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
                new String[] {"#", "Código", "Nombre", "Unidades", "Monto (S/)"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tablaMasVendidos.setModel(modelo);
    }

    private int obtenerLimite() {
        String seleccion = cbxTop.getSelectedItem().toString();
        if (seleccion.equals("Top 5")) {
            return 5;
        }
        if (seleccion.equals("Top 10")) {
            return 10;
        }
        return 0; // "Todos"
    }

    private void cargarDatos() {
        List<ProductoVendido> lista = ventaDAO.obtenerMasVendidos(obtenerLimite());

        DefaultTableModel modelo = (DefaultTableModel) tablaMasVendidos.getModel();
        modelo.setRowCount(0);

        int puesto = 1;
        for (ProductoVendido p : lista) {
            modelo.addRow(new Object[] {
                puesto++,
                p.getCodigo(),
                p.getNombre(),
                p.getUnidades(),
                String.format("%.2f", p.getMonto())
            });
        }

        if (lista.isEmpty()) {
            lblMasVendido.setText("Sin ventas");
            lblUnidadesMasVendido.setText("-");
        } else {
            ProductoVendido top = lista.get(0);
            lblMasVendido.setText(top.getNombre());
            lblUnidadesMasVendido.setText(top.getUnidades() + " unidades vendidas");
        }
    }
