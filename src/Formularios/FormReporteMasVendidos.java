    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
        List<ProductoVendido> lista = ventaDAO.obtenerMasVendidos(obtenerLimite());

if (lista.isEmpty()) {
    JOptionPane.showMessageDialog(this, "No hay ventas registradas para imprimir.",
            "Sin datos", JOptionPane.WARNING_MESSAGE);
    return;
}

String criterio = String.valueOf(cbxTop.getSelectedItem());

JFileChooser chooser = new JFileChooser();
chooser.setDialogTitle("Guardar reporte de más vendidos");
chooser.setFileFilter(new FileNameExtensionFilter("Archivo de texto (*.txt)", "txt"));
String nombreSugerido = "reporte_mas_vendidos_"
        + LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd_HHmm")) + ".txt";
chooser.setSelectedFile(new File(nombreSugerido));

if (chooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
    return;
}

File archivo = chooser.getSelectedFile();
if (!archivo.getName().toLowerCase().endsWith(".txt")) {
    archivo = new File(archivo.getParentFile(), archivo.getName() + ".txt");
}

if (archivo.exists()) {
    int r = JOptionPane.showConfirmDialog(this,
            "El archivo ya existe. ¿Deseas reemplazarlo?",
            "Confirmar", JOptionPane.YES_NO_OPTION);
    if (r != JOptionPane.YES_OPTION) {
        return;
    }
}

try {
    new ReporteMasVendidos(lista, criterio).guardar(archivo);
    JOptionPane.showMessageDialog(this, "Reporte guardado en:\n" + archivo.getAbsolutePath(),
            "Éxito", JOptionPane.INFORMATION_MESSAGE);
} catch (IOException ex) {
    JOptionPane.showMessageDialog(this, "No se pudo guardar el archivo:\n" + ex.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
}

        // TODO add your handling code here:
    }//GEN-LAST:event_btnImprimirActionPerformed

